import { pasosLanzamiento, siguientePaso } from "./.lanzamiento.mjs";
let fallos = 0;
const ok = (n, c, extra = "") => { console.log((c ? "  OK   " : "  FALLO ") + n + (extra ? "  " + extra : "")); if (!c) fallos++; };
const base = { jugado: false, anuncios: false, infantil: false, play: null, pista: null, campana: null };
let ps = pasosLanzamiento(base);
ok("7 pasos en orden y empieza por jugarlo", ps.length === 7 && siguientePaso(ps).id === "jugar");
ps = pasosLanzamiento({ ...base, jugado: true });
ok("luego los anuncios", siguientePaso(ps).id === "anuncios" && siguientePaso(ps).accion === "anuncios");
ps = pasosLanzamiento({ ...base, jugado: true, anuncios: true, play: "primer_aab", pista: "internal" });
ok("preparado pero sin subir: toca subir a la prueba cerrada", siguientePaso(ps).id === "subir");
ps = pasosLanzamiento({ ...base, jugado: true, anuncios: true, play: "subido", pista: "internal" });
ok("la prueba interna no cuenta como cerrada", siguientePaso(ps).id === "subir");
ps = pasosLanzamiento({ ...base, jugado: true, anuncios: true, play: "subido", pista: "alpha" });
ok("en prueba cerrada: probadores en la Lanzadera", siguientePaso(ps).id === "probadores" && siguientePaso(ps).accion === "lanzadera");
ps = pasosLanzamiento({ ...base, jugado: true, anuncios: true, play: "subido", pista: "alpha", campana: "abierta" });
ok("con campaña: esperar los 14 días", siguientePaso(ps).id === "catorce");
ps = pasosLanzamiento({ ...base, jugado: true, anuncios: true, play: "subido", pista: "alpha", campana: "lista" });
ok("campaña lista: pedir producción con las respuestas", siguientePaso(ps).id === "produccion" && siguientePaso(ps).boton === "Ver respuestas");
ps = pasosLanzamiento({ ...base, jugado: true, anuncios: true, play: "subido", pista: "production" });
ok("en producción: todo hecho", siguientePaso(ps) === null && ps.every((p) => p.hecho));
ok("infantil: anuncios para familias", pasosLanzamiento({ ...base, infantil: true })[1].titulo === "Anuncios para familias");
console.log(`== ${fallos} fallos ==`);
if (fallos) process.exit(1);
