import { aconsejar } from "./.asesor.mjs";
let fallos = 0;
const ok = (n, c) => { console.log((c ? "  OK   " : "  FALLO ") + n); if (!c) fallos++; };
const f = (nivel, intentos, sesiones, ganados, salidas, muertes) => ({ version: 1, nivel, intentos, sesiones, ganados, salidas, reintentos: 0, muertes_medias: muertes, segundos_medios: 50, estrellas_medias: 2 });
const base = { genero: "plataformas", publico: "todos", funciones: {}, publicado: true, anuncios: true, niveles: ["A", "B", "C"], informe: null,
  ingresos: { jugadores_total: 200, d1: 40, d7: 12, total_euros: 3, compras: 2 }, eventosProgramados: 0 };
const ids = (d) => aconsejar(d).map((c) => c.id);

let r = ids({ ...base, publicado: false, anuncios: false, ingresos: null });
ok("sin publicar: publicar primero, luego anuncios", r[0] === "publicar" && r[1] === "anuncios" && r.length === 3);
r = ids({ ...base, ingresos: { ...base.ingresos, jugadores_total: 7 } });
ok("pocos jugadores: conseguir los primeros", r[0] === "primeros");
ok("pocos jugadores: no opina de retención", !r.includes("avisos") && !r.includes("evento"));
r = aconsejar({ ...base, funciones: { avisos: false }, ingresos: { ...base.ingresos, d1: 12 } });
ok("D1 bajo y avisos apagados: encender avisos", r[0].id === "avisos" && r[0].accion.tipo === "funcion" && r[0].accion.op.avisos === true);
r = ids({ ...base, ingresos: { ...base.ingresos, d1: 12 } });
ok("D1 bajo con todo encendido: mejorar el primer nivel", r.includes("primer_nivel"));
r = ids({ ...base, genero: "clicker", funciones: { pase: false }, ingresos: { ...base.ingresos, d1: 12 } });
ok("D1 bajo en clicker sin pase: misiones y pase", r.includes("pase"));
r = ids({ ...base, ingresos: { ...base.ingresos, d7: 3 } });
ok("D7 bajo sin eventos: programar evento", r.includes("evento"));
r = ids({ ...base, ingresos: { ...base.ingresos, d7: 3 }, eventosProgramados: 1 });
ok("con evento ya programado no lo repite", !r.includes("evento"));
r = ids({ ...base, funciones: { tienda: false } });
ok("200 jugadores sin tienda: abrir tienda", r.includes("tienda"));
r = ids({ ...base, ingresos: { ...base.ingresos, compras: 0 } });
ok("muchos jugadores y cero compras: oferta", r.includes("oferta"));
r = ids({ ...base, genero: "arena", funciones: { online: false } });
ok("arena sin online: encender online", r.includes("online"));
const ninos = aconsejar({ ...base, genero: "arena", publico: "infantil", funciones: { online: false, tienda: false, avisos: false }, ingresos: { ...base.ingresos, d1: 5, compras: 0 } });
ok("para niños: nunca tienda, avisos ni online", !ninos.some((c) => ["tienda", "avisos", "online", "oferta"].includes(c.id) || (c.accion.tipo === "funcion" && (c.accion.op.tienda || c.accion.op.avisos || c.accion.op.online))));
r = aconsejar({ ...base, informe: [f(0, 100, 100, 95, 2, 0.1), f(1, 90, 80, 30, 50, 3.5), f(2, 40, 30, 30, 2, 1)] });
ok("nivel atascado: arreglo con instrucción del taller", r[0].id === "nivel" && r[0].accion.tipo === "arreglar" && r[0].accion.instruccion.includes("nivel 2"));
r = ids({ ...base, informe: [f(0, 100, 100, 95, 2, 0.1), f(1, 90, 80, 30, 50, 3.5), f(2, 40, 30, 30, 2, 1)] });
ok("nivel atascado con muchos jugadores: propone prueba A/B", r.includes("ab"));
r = ids({ ...base, pruebaAb: true, informe: [f(0, 100, 100, 95, 2, 0.1), f(1, 90, 80, 30, 50, 3.5), f(2, 40, 30, 30, 2, 1)] });
ok("con una prueba en marcha no la repite", !r.includes("ab"));
ok("como mucho 3 consejos", aconsejar({ ...base, publicado: false, anuncios: false, genero: "arena", funciones: { online: false } }).length === 3);
ok("todo en su punto: sin consejos", aconsejar(base).length === 0);
console.log(fallos ? `== ${fallos} fallos ==` : "== 0 fallos ==");
process.exit(fallos ? 1 : 0);
