import { diagnosticar } from "./.aprendizaje.mjs";
const f = (nivel, intentos, sesiones, ganados, salidas, muertes, version = 2) => ({ version, nivel, intentos, sesiones, ganados, salidas, reintentos: 0, muertes_medias: muertes, segundos_medios: 50, estrellas_medias: 2 });
let fallos = 0;
const ok = (n, c) => { console.log((c ? "  OK   " : "  FALLO ") + n); if (!c) fallos++; };
const nombres = ["Tejados", "Chimeneas", "Antenas", "La torre"];
let d = diagnosticar([f(0, 100, 100, 95, 2, 0.1), f(1, 90, 80, 86, 2, 0.1), f(2, 120, 70, 20, 60, 3.2), f(3, 10, 8, 2, 5, 4), f(0, 50, 50, 10, 30, 3, 1)], nombres);
ok("usa la última versión", d.version === 2);
ok("nivel 3: abandono", d.consejos.some((c) => c.nivel === 2 && c.tipo === "abandono" && c.instruccion === "Rehaz el nivel 3 más fácil, que la gente lo abandona"));
ok("nivel 2: demasiado fácil", d.consejos.some((c) => c.nivel === 1 && c.tipo === "facil"));
ok("el primer nivel fácil no es un problema", !d.consejos.some((c) => c.nivel === 0));
ok("sin datos suficientes no opina (nivel 4: 10 intentos)", !d.consejos.some((c) => c.nivel === 3));
ok("llegan al nivel 3 el 70 %", Math.abs(d.niveles[2].llegan - 0.7) < 1e-9);
ok("jugadores = sesiones del nivel 1", d.jugadores === 100);
d = diagnosticar([f(0, 100, 100, 20, 10, 3), f(1, 80, 30, 10, 20, 4), f(2, 50, 20, 5, 10, 5)], nombres);
ok("casi todo difícil: consejo general primero", d.consejos[0].tipo === "general" && d.consejos[0].instruccion === "Hazlo más fácil");
d = diagnosticar([f(0, 100, 100, 80, 5, 1), f(1, 60, 30, 50, 2, 1)], nombres);
ok("embudo del nivel 1 al 2", d.consejos.some((c) => c.tipo === "embudo" && c.nivel === 0));
ok("sin filas", diagnosticar([], nombres).suficiente === false);
console.log(fallos ? `== ${fallos} fallos ==` : "== 0 fallos ==");
process.exit(fallos ? 1 : 0);
