## Editor manual de niveles (app): que letras se pueden poner en cada genero, cuantas tiene que
## haber de las obligatorias y el tamano. Los niveles editados a mano no se rehacen: si el
## analizador o el bot no los superan, el cambio falla (y se devuelven las tuercas).
_PLATAFORMAS_EDITOR = {"letras": ".#PGC^R=HJMVIEKFB", "una": "PG", "filas": [8, 24], "ancho": [16, 300]}
EDITOR: dict[str, dict] = {
	"plataformas": _PLATAFORMAS_EDITOR,
	"runner": {**_PLATAFORMAS_EDITOR, "letras": ".#PGC^RHJMVIEKF"},
	"volador": {"letras": ".#PGCRHJMVI", "una": "PG", "filas": [10, 24], "ancho": [20, 400]},
	"rompebloques": {"letras": ".123#CLM", "una": "", "filas": [3, 12], "ancho": [9, 9]},
	"cajas": {"letras": ".#PBOQR", "una": "", "filas": [5, 12], "ancho": [5, 12]},
	"topos": {"letras": ".o", "una": "", "filas": [2, 4], "ancho": [3, 4]},
	"aldea": {"letras": ".#HGEMKCAO", "una": "H", "filas": [14, 24], "ancho": [14, 24]},
	"arena": {"letras": ".#*BPR", "una": "P", "filas": [11, 31], "ancho": [9, 25]},
	"laberinto": {"letras": ".#PCXLD", "una": "P", "filas": [7, 15], "ancho": [5, 11]},
	"golf": {"letras": ".#BHWS", "una": "BH", "filas": [8, 18], "ancho": [5, 11]},
	"imperio": {"letras": ".~^TBOPEcqlwht#", "una": "P", "filas": [16, 34], "ancho": [14, 28]},
}


def problemas_mapa(genero: str, mapa: list[str]) -> list[str]:
	"""Reglas rapidas del editor (las mismas en el servidor). El analizador y el bot hacen el resto."""
	e = EDITOR.get(genero)
	if not e:
		return [f"los niveles de un juego de tipo {genero} aun no se pueden editar a mano"]
	out = []
	if not isinstance(mapa, list) or not all(isinstance(f, str) for f in mapa):
		return ["el mapa tiene que ser una lista de filas de texto"]
	if not (e["filas"][0] <= len(mapa) <= e["filas"][1]):
		out.append(f"el nivel tiene que tener entre {e['filas'][0]} y {e['filas'][1]} filas")
	anchos = {len(f) for f in mapa}
	if len(anchos) != 1:
		out.append("todas las filas tienen que medir lo mismo")
	elif not (e["ancho"][0] <= next(iter(anchos)) <= e["ancho"][1]):
		out.append(f"el nivel tiene que medir entre {e['ancho'][0]} y {e['ancho'][1]} casillas de ancho")
	raras = sorted({c for f in mapa for c in f if c not in e["letras"]})
	if raras:
		out.append("casillas que no existen en este tipo de juego: " + " ".join(raras))
	for c in e["una"]:
		n = sum(f.count(c) for f in mapa)
		if n != 1:
			out.append({"P": "tiene que haber exactamente un punto de salida del heroe",
				"G": "tiene que haber exactamente una meta"}.get(c, f"tiene que haber exactamente un '{c}'"))
	return out


## Generos que se pueden ver en 3D y su vista por defecto (el resto solo existe en 2D).
## Carreras nace en 3D (coches con camara detras); plataformas, runner y volador nacen en 2D y
## pasan a 2.5D (bloques de verdad, fondo con profundidad) si la idea o el taller lo piden.
VISTA_3D: dict[str, str] = {"carreras": "3d", "plataformas": "2d", "runner": "2d", "volador": "2d", "royale": "3d", "supervivencia": "3d", "duelo": "3d"}


def vista(d: dict) -> str:
	"""Vista con la que se dibuja un diseno: "3d" o "2d" (los generos sin 3D siempre "2d")."""
	g = d.get("genero", "plataformas")
	if g not in VISTA_3D:
		return "2d"
	return d.get("vista", VISTA_3D[g])


def con_vista_3d() -> list[str]:
	return [g for g in GENEROS if g in VISTA_3D]


CAMPOS = ["kit", "etiqueta", "jefe", "disparo", "poderes", "extras", "enemigos", "enemigos_fijos", "corre_solo",
	"estricto", "generar", "parametros", "enemigos_nivel", "textos", "frase", "claves", "pedir", "convertir", "no_puedo", "clip_saltar", "corto", "aso"]


def de(d_o_genero: "dict | str | None") -> dict:
	"""Ficha del genero de un diseno (o de un nombre). Sin genero = plataformas."""
	g = d_o_genero.get("genero", "plataformas") if isinstance(d_o_genero, dict) else (d_o_genero or "plataformas")
	return GENEROS.get(g, GENEROS["plataformas"])


def ids() -> list[str]:
	return list(GENEROS)


def para_servidor() -> dict:
	"""Lo que necesita plan-change (TypeScript) para aplicar las mismas reglas que el taller."""
	return {g: {**{k: v[k] for k in ("jefe", "disparo", "poderes", "extras", "enemigos", "enemigos_fijos", "corre_solo")},
		"vista_3d": g in VISTA_3D, "nace_3d": VISTA_3D.get(g) == "3d"} for g, v in GENEROS.items()}


def comprobar() -> list[str]:
	"""Errores de coherencia del registro (lo usan las pruebas y nuevo_genero)."""
	errores = []
	if set(ORDEN) != set(GENEROS):
		errores.append("ORDEN debe tener exactamente los mismos generos que GENEROS")
	kits = [v["kit"] for v in GENEROS.values()]
	if len(set(kits)) != len(kits):
		errores.append("dos generos usan el mismo 'kit'")
	for g, v in GENEROS.items():
		for c in CAMPOS:
			if c not in v:
				errores.append(f"{g}: falta el campo '{c}'")
		if v.get("jefe") and not v.get("enemigos"):
			errores.append(f"{g}: un jefe necesita arte de enemigos")
		if any(len(c) > 30 for c in v.get("corto", ("",))):
			errores.append(f"{g}: 'corto' no cabe en el subtitulo del App Store (30)")
		if len(v.get("frase", ("", ""))[0]) > 80:
			errores.append(f"{g}: la frase en espanol no cabe en la descripcion breve de Google Play (80)")
	return errores
